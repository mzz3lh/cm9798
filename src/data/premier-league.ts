// The 2026/27 Premier League: the 20 clubs, their grounds and their squads.
// The clubs are this season's (Coventry, Ipswich and Hull promoted; Wolves,
// Burnley and West Ham relegated). The squads are the latest known to us,
// from the end of 2025/26, so the summer 2026 window's moves are missing;
// the data phase replaces them with converted EA Sports FC / Opta ratings.
// Ratings are rough hand estimates on the CM scales, and anything not given
// is left at 0 and generated, as the original did.
//
// Each player is one line: "Name; Nation; Age; Positions; Ability", with
// "Name=Short" when commentary should use a different name.

import { makePlayer, type PlayerSeed } from '../engine/generate';
import type { Position, Team } from '../engine/types';
import { ARSENAL, LIVERPOOL, MAN_CITY } from './squads';

export interface ClubInfo {
  team: Team;
  /** Ground capacity, for gate receipts. */
  capacity: number;
}

function parse(line: string): PlayerSeed {
  const [nameField, nation, age, positions, ability] = line.split(';').map(s => s.trim());
  const [name, shortName] = nameField.split('=');
  return { name, shortName, nation, age: Number(age), positions: positions.split('/') as Position[], ability: Number(ability) };
}

export function club(
  id: string, name: string, shortName: string, reputation: number, stadium: string, capacity: number,
  colours: Team['colours'], lines: string[],
): ClubInfo {
  const squad = lines.map(parse).map(s => makePlayer({ ...s, id: `${id}-${s.name}`.toLowerCase().replace(/[^a-z0-9]+/g, '-') }));
  return { team: { id, name, shortName, reputation, stadium, colours, squad }, capacity };
}

const withPlayers = (t: Team, lines: string[]): Team => ({
  ...t,
  squad: [...t.squad, ...lines.map(parse).map(s => makePlayer({ ...s, id: `${t.id}-${s.name}`.toLowerCase().replace(/[^a-z0-9]+/g, '-') }))],
});

